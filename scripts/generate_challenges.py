def generate_notebooks(config: dict[str, str]) -> tuple[Path, Path]:
    base = {"metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}, "language_info": {"name": "python", "version": "3"}}, "nbformat": 4, "nbformat_minor": 5}
    student = ROOT / "public" / "evidence" / "fraud_analysis.ipynb"
    solution = ROOT / "facilitator" / "fraud_analysis_completed.ipynb"
    for path, completed in ((student, False), (solution, True)):
        document = dict(base)
        document["cells"] = notebook_cells(config, completed)
        path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    return student, solution


def main() -> None:
    config = load_env(CONFIG_PATH)
    require(
        config,
        "IMAGE_FLAG", "IMAGE_CHARADE", "IMAGE_NEXT", "IMAGE_SOURCE", "IMAGE_OUTPUT",
        "DNS_FLAG", "DNS_CHARADE", "DNS_NEXT", "DNS_DOMAIN",
        "WEBSITE_FLAG", "WEBSITE_CHARADE", "WEBSITE_NEXT",
        "NOTEBOOK_FLAG", "NOTEBOOK_CHARADE", "NOTEBOOK_NEXT",
        "CHAT_FLAG", "CHAT_SECRET_NOTE", "CHAT_NEXT",
        "ADMIN_USERNAME", "FINAL_PASSWORD", "GENERATION_SEED",
    )
    rng = random.Random(config["GENERATION_SEED"])
    outputs = [
        generate_image(config),
        generate_dns(config, rng),
        generate_website(config),
        generate_chat_secret(config),
        generate_admin_credentials(config),
        *generate_notebooks(config),
    ]
    print("Generated Citadelle challenge assets:")
    for output in outputs:
        print(f"  - {output.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
