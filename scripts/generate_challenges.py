ROOT = Path(__file__).resolve().parents[1]
CONFIG_PATH = ROOT / "facilitator" / "challenge.env"


def load_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for number, raw_line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            raise ValueError(f"{path}:{number}: expected KEY=VALUE")
        key, raw_value = line.split("=", 1)
        key = key.strip()
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", key):
            raise ValueError(f"{path}:{number}: invalid key {key!r}")
        raw_value = raw_value.strip()
        try:
            value = json.loads(raw_value) if raw_value.startswith('"') else raw_value
        except json.JSONDecodeError as error:
            raise ValueError(f"{path}:{number}: invalid quoted value") from error
        values[key] = str(value)
    return values


def require(config: dict[str, str], *keys: str) -> None:
    missing = [key for key in keys if not config.get(key)]
    if missing:
        raise ValueError(f"Missing configuration: {', '.join(missing)}")


def message(config: dict[str, str], prefix: str) -> str:
    return "\n\n".join(
        [config[f"{prefix}_FLAG"], config[f"{prefix}_CHARADE"], config[f"{prefix}_NEXT"]]
    )


def generate_image(config: dict[str, str]) -> Path:
    source = ROOT / config["IMAGE_SOURCE"]
    output = ROOT / config["IMAGE_OUTPUT"]
    output.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, output)
    marker = (
        "\n\n[CITADELLE_TRAINING_EVIDENCE]\n"
        f"{message(config, 'IMAGE')}\n"
        "[END_CITADELLE_TRAINING_EVIDENCE]\n"
    )
    with output.open("ab") as image:
        image.write(marker.encode("utf-8"))
    return output


def generate_dns(config: dict[str, str], rng: random.Random) -> Path:
    encoded = base64.b64encode(message(config, "DNS").encode()).decode()
    fragments = [encoded[index : index + 24] for index in range(0, len(encoded), 24)]
    suspicious = [
        f"2026-07-27T09:{14 + index // 4:02d}:{2 + index * 7:02d}Z 10.20.8.14 TXT "
        f"{index + 1:02d}-{fragment}.{config['DNS_DOMAIN']} NOERROR"
        for index, fragment in enumerate(fragments)
    ]
    rng.shuffle(suspicious)
    noise = [
        "2026-07-27T09:13:50Z 10.20.8.14 A portal.citadelle.local 10.20.2.8",
        "2026-07-27T09:13:53Z 10.20.4.21 AAAA updates.training.local NOERROR",
        "2026-07-27T09:14:05Z 10.20.4.21 A cdn.training.local 192.0.2.18",
        "2026-07-27T09:14:13Z 10.20.3.9 A analytics.training.local 192.0.2.30",
        "2026-07-27T09:14:21Z 10.20.4.21 A mail.citadelle.local 10.20.2.15",
        "2026-07-27T09:14:29Z 10.20.6.42 TXT status.telemetry.training.local NOERROR",
        "2026-07-27T09:14:54Z 10.20.6.42 TXT U29mdHdhcmVVcGRhdGU=.telemetry.training.local NOERROR",
        "2026-07-27T09:15:04Z 10.20.8.14 A gateway.citadelle.local 10.20.1.1",
        "2026-07-27T09:15:22Z 10.20.4.21 A help.citadelle.local 10.20.2.22",
        "2026-07-27T09:15:58Z 10.20.8.14 A portal.citadelle.local 10.20.2.8",
    ]
    rows = noise + suspicious
    rng.shuffle(rows)
    output = ROOT / "public" / "evidence" / "network_capture.log"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "# CITADELLE SECURITY OPERATIONS — DNS resolver export\n"
        "# Training data. Rows may not be in capture order.\n"
        "# Format: timestamp client record query response\n"
        + "\n".join(rows)
        + "\n",
        encoding="utf-8",
    )
    return output


def generate_website(config: dict[str, str]) -> Path:
    encoded = base64.b64encode(message(config, "WEBSITE").encode()).decode()
    size = (len(encoded) + 2) // 3
    fragments = [encoded[index : index + size] for index in range(0, len(encoded), size)]
    output = ROOT / "lib" / "generated-challenge.ts"
    output.write_text(
        "// Generated by scripts/generate_challenges.py. Do not edit by hand.\n"
        f"export const sourceClueParts = {json.dumps(fragments)} as const;\n"
        f"export const trainingPasswordHash = {json.dumps(hashlib.sha256(config['FINAL_PASSWORD'].encode()).hexdigest())};\n",
        encoding="utf-8",
    )
    return output


def generate_chat_secret(config: dict[str, str]) -> Path:
    output = ROOT / "server" / "generated-chat-secret.ts"
    output.parent.mkdir(parents=True, exist_ok=True)
    protected_note = "\n\n".join(
        [config["CHAT_FLAG"], config["CHAT_SECRET_NOTE"], config["CHAT_NEXT"]]
    )
    output.write_text(
        'import "server-only";\n\n'
        "// Generated by scripts/generate_challenges.py. Do not edit by hand.\n"
        f"export const protectedSupportNote = {json.dumps(protected_note)};\n",
        encoding="utf-8",
    )
    return output


def generate_admin_credentials(config: dict[str, str]) -> Path:
    output = ROOT / "server" / "generated-admin-credentials.ts"
    output.parent.mkdir(parents=True, exist_ok=True)
    salt = hashlib.sha256(
        f"citadelle-admin:{config['GENERATION_SEED']}".encode()
    ).hexdigest()[:32]
    password_hash = hashlib.pbkdf2_hmac(
        "sha256",
        config["FINAL_PASSWORD"].encode(),
        bytes.fromhex(salt),
        210_000,
    ).hex()
    signing_key = hashlib.sha256(
        f"{config['GENERATION_SEED']}:{config['FINAL_PASSWORD']}:session".encode()
    ).hexdigest()
    output.write_text(
        'import "server-only";\n\n'
        "// Generated by scripts/generate_challenges.py. Do not edit by hand.\n"
        f"export const adminUsername = {json.dumps(config['ADMIN_USERNAME'])};\n"
        f"export const adminPasswordSalt = {json.dumps(salt)};\n"
        f"export const adminPasswordHash = {json.dumps(password_hash)};\n"
        f"export const adminSessionSigningKey = {json.dumps(signing_key)};\n",
        encoding="utf-8",
    )
    return output


